package com.example.solexclusive.Model;

public class Brands {
    private int id_brand;
    private String name;

    public Brands() {
    }

    public int getId_brand() {
        return id_brand;
    }

    public void setId_brand(int id_brand) {
        this.id_brand = id_brand;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }
}
